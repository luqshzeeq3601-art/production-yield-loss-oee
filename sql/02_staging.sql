-- 02_staging.sql — load heap mirroring source CSV structure.
--
-- Every table reflects one generated/imported artifact column-for-column so
-- the P2-003 loader can COPY directly. Staging tables are intentionally heap
-- tables: no primary keys, no foreign keys, all columns nullable, no
-- analytical calculations. Validation happens in analytics CHECK constraints.
-- Column names are lowercase by convention; the P2-003 loader lowercases CSV
-- headers on import (e.g. MetroPT-3 "TP2" -> tp2).

