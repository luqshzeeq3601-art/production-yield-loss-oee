-- MetroPT-3 processed readings (data/processed/metropt3_readings.csv).
-- operating_state is a project-assumption rule, not an observed label;
-- failure_event_id 0 means "no documented failure window".
CREATE TABLE IF NOT EXISTS staging.metropt3_readings (
    source_index BIGINT,
    timestamp TIMESTAMP,
    tp2 DOUBLE PRECISION,
    tp3 DOUBLE PRECISION,
    h1 DOUBLE PRECISION,
    dv_pressure DOUBLE PRECISION,
    reservoirs DOUBLE PRECISION,
    oil_temperature DOUBLE PRECISION,
    motor_current DOUBLE PRECISION,
    comp DOUBLE PRECISION,
    dv_eletric DOUBLE PRECISION,
    towers DOUBLE PRECISION,
    mpg DOUBLE PRECISION,
    lps DOUBLE PRECISION,
    pressure_switch DOUBLE PRECISION,
    oil_level DOUBLE PRECISION,
    caudal_impulses DOUBLE PRECISION,
    operating_state TEXT,
    failure_event_id INTEGER,
    in_failure_window SMALLINT,
    in_prefailure_window SMALLINT
);

-- MetroPT-3 documented failure intervals (data/processed/metropt3_failure_intervals.csv).
CREATE TABLE IF NOT EXISTS staging.metropt3_failure_intervals (
    event_id INTEGER,
    kind TEXT,
    window_start TIMESTAMP,
    window_end TIMESTAMP,
    readings_in_window INTEGER,
    prefailure_readings INTEGER
);

-- MetroPT-3 operating-state periods (data/processed/metropt3_state_periods.csv).
CREATE TABLE IF NOT EXISTS staging.metropt3_state_periods (
    period_id BIGINT,
    operating_state TEXT,
    start_timestamp TIMESTAMP,
    end_timestamp TIMESTAMP,
    row_count INTEGER,
    duration_seconds DOUBLE PRECISION
);

-- MES hourly production incl. derived A/P/Q (data/processed/mes_production_hourly.csv).
-- Derived availability/performance/quality/oee are staged for traceability but
-- are NOT authoritative: analytics recomputes them from components.
CREATE TABLE IF NOT EXISTS staging.mes_production_hourly (
    line TEXT,
    shift TEXT,
    date DATE,
    hour_in_shift SMALLINT,
    hour_start TIMESTAMP,
    product TEXT,
    planned_time_min DOUBLE PRECISION,
    run_time_min DOUBLE PRECISION,
    ideal_cycle_time_s DOUBLE PRECISION,
    actual_cycle_time_s DOUBLE PRECISION,
    total_count INTEGER,
    good_count INTEGER,
    scrap_count INTEGER,
    availability DOUBLE PRECISION,
    performance DOUBLE PRECISION,
    quality DOUBLE PRECISION,
    oee DOUBLE PRECISION
);

